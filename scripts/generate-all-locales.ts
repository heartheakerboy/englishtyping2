// Fallback generator for remaining Indian and regional languages
const ALL_LANGS = [
  "hi", "mr", "gu", "ta", "te", "kn", "ml", "pa", "bn", "ur", "ar", "es", "fr", "de", "pt", "ru", "ja", "ko", "zh"
];

ALL_LANGS.forEach((lang) => {
  const t = TRANSLATIONS[lang] || TRANSLATIONS["hi"];
  const outDir = path.join("public/locales", lang);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  fs.writeFileSync(path.join(outDir, "leaderboard.json"), JSON.stringify(t.leaderboard, null, 2));
  fs.writeFileSync(path.join(outDir, "dashboard.json"), JSON.stringify(t.dashboard, null, 2));
  fs.writeFileSync(path.join(outDir, "profile.json"), JSON.stringify(t.profile, null, 2));
});

